export interface ProcessorGenerationValue { family: string; name: string; generation: number }

/** Lista plana de valores, sin repetidos dentro de cada procesador, en el orden en que se cargan al catálogo. */
export function processorGenerationValues(): ProcessorGenerationValue[] {
  const out: ProcessorGenerationValue[] = [];
  const seen = new Set<string>();
  for (const g of PROCESSOR_GENERATIONS) {
    for (const sku of g.skus.split(/\s+/).filter(Boolean)) {
      const name = sku;
      const key = `${g.family}|${name}`;
      if (seen.has(key)) continue;
      seen.add(key);
      out.push({ family: g.family, name, generation: g.generation });
    }
  }
  return out;
}
