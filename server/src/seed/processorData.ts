/**
 * Generaciones de procesador: el número de modelo tal como lo muestra la BIOS, pero sin repetir la familia
 * (por ejemplo "6300U", no "i5-6300U", porque el procesador ya dice "Intel Core i5" en su propio campo).
 * Es el punto de partida del catálogo "Generaciones de procesador": cada valor pertenece a su procesador
 * (Intel Core i5, AMD Ryzen 5…) y en el equipo solo salen los del procesador elegido.
 * Cada empresa los puede editar, ampliar y reordenar. Ordenados por generación y luego por número.
 */

export interface ProcessorGeneration {
  /** Nombre del valor en el catálogo "Procesadores". */
  family: string;
  /** Generación (para Ryzen, la serie: 1000 → 1). */
  generation: number;
  /** Números de modelo, separados por espacio (sin el prefijo de familia, p. ej. "6300U" no "i5-6300U"). */
  skus: string;
}

